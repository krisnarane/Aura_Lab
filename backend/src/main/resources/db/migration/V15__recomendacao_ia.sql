-- RNF0044: preferencias explicitas, conversa, avaliacao e versoes do modelo.
create table cliente_preferencia (
  cliente_id bigint not null references cliente(id),
  categoria_codigo varchar(40) not null references categoria_produto(codigo),
  primary key (cliente_id, categoria_codigo)
);

create table ia_modelo (
  id bigint generated by default as identity primary key,
  versao varchar(100) not null unique,
  modelo_base varchar(100) not null,
  endpoint text not null,
  job_nome text not null,
  dataset_sha256 char(64) not null,
  manifesto jsonb not null,
  ativo boolean not null default false,
  criado_em timestamptz not null default current_timestamp
);
create unique index ia_modelo_ativo_unico on ia_modelo(ativo) where ativo;

create table ia_conversa (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references cliente(id),
  criada_em timestamptz not null default current_timestamp
);
create index ia_conversa_cliente on ia_conversa(cliente_id, criada_em desc);

create table ia_mensagem (
  id bigint generated by default as identity primary key,
  conversa_id bigint not null references ia_conversa(id),
  papel varchar(10) not null check (papel in ('USER', 'ASSISTANT')),
  texto text not null,
  produtos_ids jsonb not null default '[]'::jsonb,
  modelo_versao varchar(100),
  criada_em timestamptz not null default current_timestamp,
  check (char_length(texto) between 1 and 6000)
);
create index ia_mensagem_conversa on ia_mensagem(conversa_id, id);

create table ia_avaliacao (
  resposta_id bigint primary key references ia_mensagem(id),
  util boolean not null,
  motivo varchar(300),
  correcao text,
  atualizada_em timestamptz not null default current_timestamp,
  check (correcao is null or char_length(correcao) between 1 and 6000)
);
