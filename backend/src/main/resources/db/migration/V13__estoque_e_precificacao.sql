-- RF0051/RF0052, RN0013, RN0050, RN0061, RN0062 e RNF0064.
create table grupo_precificacao (
  codigo varchar(40) primary key,
  descricao varchar(120) not null,
  percentual_margem numeric(5,2) not null check (percentual_margem >= 0)
);
insert into grupo_precificacao values
  ('PADRAO', 'Padrão', 50.00), ('PREMIUM', 'Premium', 80.00), ('BASICO', 'Básico', 30.00);
alter table produto add column grupo_precificacao_codigo varchar(40) references grupo_precificacao(codigo);
update produto set grupo_precificacao_codigo = 'PADRAO';
alter table produto alter column grupo_precificacao_codigo set not null;
alter table produto add column valor_custo numeric(12,2) check (valor_custo >= 0);
create table entrada_estoque (
  id bigint generated by default as identity primary key,
  produto_id bigint not null references produto(id),
  quantidade integer not null check (quantidade > 0),
  valor_custo numeric(12,2) not null check (valor_custo > 0),
  data_entrada date not null,
  preco_calculado numeric(12,2) not null,
  registrada_em timestamp with time zone not null
);
create index entrada_estoque_produto_data on entrada_estoque(produto_id, data_entrada desc, id desc);
