-- Módulo de vendas (DRS grupo "Gerenciar Vendas Eletrônicas").
-- Escopo desta fase: carrinho (RF0031/RF0032/RN0031), realizar/finalizar compra
-- (RF0033/RF0038 -> status EM_PROCESSAMENTO), endereço (RF0035/RN0023), frete (RF0034),
-- pagamento com cartões e cupons (RF0036/RF0037/RN0024/RN0025) e regras RN0033–RN0036.
-- Fora de escopo (não modelado aqui): validação/aprovação do pagamento, baixa de estoque,
-- bloqueio/expiração do carrinho e o processo de troca.

-- Carrinho de compra: um repositório temporário por cliente (RF0031).
create table carrinho (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null unique references cliente(id),
  criado_em timestamp with time zone not null,
  atualizado_em timestamp with time zone not null
);

create table item_carrinho (
  id bigint generated by default as identity primary key,
  carrinho_id bigint not null references carrinho(id),
  produto_id bigint not null references produto(id),
  quantidade integer not null check (quantidade > 0),
  unique (carrinho_id, produto_id)
);
create index item_carrinho_carrinho on item_carrinho(carrinho_id);

-- Cupom: promocional (desconto, geral) ou de troca (crédito do cliente).
-- Nesta fase os cupons usados são pré-carregados; o único cupom gerado é o de troco
-- do RN0036 (quando o valor dos cupons de troca supera o total da compra).
create table cupom (
  id bigint generated by default as identity primary key,
  codigo varchar(20),
  tipo varchar(20) not null check (tipo in ('PROMOCIONAL', 'TROCA')),
  cliente_id bigint references cliente(id),
  valor numeric(12, 2) check (valor is null or valor >= 0),
  percentual numeric(5, 2) check (percentual is null or (percentual >= 0 and percentual <= 100)),
  situacao varchar(20) not null default 'ATIVO' check (situacao in ('ATIVO', 'UTILIZADO')),
  validade date,
  origem varchar(120),
  criado_em timestamp with time zone not null
);
create function atribuir_codigo_cupom() returns trigger language plpgsql as $$
begin
 if TG_OP = 'INSERT' then NEW.codigo := 'CUP-' || lpad(NEW.id::text, greatest(6, length(NEW.id::text)), '0');
 elsif NEW.codigo is distinct from OLD.codigo then raise exception 'Código do cupom é imutável'; end if;
 return NEW;
end $$;
create trigger codigo_cupom before insert or update of codigo on cupom for each row execute function atribuir_codigo_cupom();
alter table cupom alter column codigo set not null;
create index cupom_cliente on cupom(cliente_id);

-- Pedido: criado na finalização com status EM_PROCESSAMENTO (RF0038). O endereço de
-- entrega é copiado (snapshot) para preservar a compra mesmo que o endereço mude depois;
-- entrega_endereco_id referencia o endereço do perfil quando existente/incorporado.
-- O snapshot reproduz a composição da RN0023, inclusive o campo opcional observações.
create table pedido (
  id bigint generated by default as identity primary key,
  codigo varchar(20),
  cliente_id bigint not null references cliente(id),
  status varchar(30) not null,
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  desconto numeric(12, 2) not null default 0 check (desconto >= 0),
  frete numeric(12, 2) not null default 0 check (frete >= 0),
  total numeric(12, 2) not null check (total >= 0),
  cupom_promocional_id bigint references cupom(id),
  cupom_troca_gerado_id bigint references cupom(id),
  entrega_endereco_id bigint references endereco(id),
  entrega_apelido varchar(60),
  entrega_tipo_residencia varchar(40) not null,
  entrega_tipo_logradouro varchar(40) not null,
  entrega_logradouro varchar(160) not null,
  entrega_numero varchar(20) not null,
  entrega_bairro varchar(100) not null,
  entrega_cep varchar(8) not null,
  entrega_cidade varchar(100) not null,
  entrega_estado varchar(60) not null,
  entrega_pais varchar(60) not null,
  entrega_complemento varchar(100),
  entrega_observacoes varchar(500),
  criado_em timestamp with time zone not null
);
create function atribuir_codigo_pedido() returns trigger language plpgsql as $$
begin
 if TG_OP = 'INSERT' then NEW.codigo := 'PED-' || lpad(NEW.id::text, greatest(6, length(NEW.id::text)), '0');
 elsif NEW.codigo is distinct from OLD.codigo then raise exception 'Código do pedido é imutável'; end if;
 return NEW;
end $$;
create trigger codigo_pedido before insert or update of codigo on pedido for each row execute function atribuir_codigo_pedido();
alter table pedido alter column codigo set not null;
create index pedido_cliente on pedido(cliente_id, criado_em desc);

-- Itens do pedido: snapshot de código, nome e preço unitário no momento da compra.
create table item_pedido (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references pedido(id),
  produto_id bigint not null references produto(id),
  produto_codigo varchar(20) not null,
  produto_nome varchar(150) not null,
  preco_unitario numeric(12, 2) not null check (preco_unitario >= 0),
  quantidade integer not null check (quantidade > 0),
  subtotal numeric(12, 2) not null check (subtotal >= 0)
);
create index item_pedido_pedido on item_pedido(pedido_id);

-- Composição de pagamento: cada parcela é um cartão (valor alocado) ou um cupom de troca
-- (valor de face). O cupom promocional entra como desconto no próprio pedido, não aqui.
create table pagamento_parte (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references pedido(id),
  tipo varchar(20) not null check (tipo in ('CARTAO', 'CUPOM_TROCA')),
  valor numeric(12, 2) not null check (valor >= 0),
  descricao varchar(160) not null,
  cartao_id bigint references cartao(id),
  cupom_id bigint references cupom(id)
);
create index pagamento_parte_pedido on pagamento_parte(pedido_id);
