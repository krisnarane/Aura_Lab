-- UC05: reservas, pagamento, trocas e notificações. V1--V8 permanecem imutáveis.
alter table pedido add column legado boolean not null default true;
alter table pedido alter column legado set default false;
alter table pedido add column pagamento_status varchar(20) not null default 'PENDENTE';
alter table pedido add column motivo_resultado varchar(200);
alter table pedido add column chave_checkout varchar(80);
alter table pedido add column resumo_checkout varchar(64);
alter table pedido add column troco_previsto numeric(12,2) not null default 0 check(troco_previsto >= 0);
create unique index pedido_checkout_unico on pedido(cliente_id,chave_checkout) where chave_checkout is not null;
alter table cupom drop constraint cupom_situacao_check;
alter table cupom add constraint cupom_situacao_check check(situacao in ('ATIVO','RESERVADO','UTILIZADO'));
alter table cupom add column pedido_reserva_id bigint references pedido(id);
alter table pagamento_parte add column resultado_validacao varchar(20);

create table reserva_estoque (
 id bigint generated by default as identity primary key,
 cliente_id bigint not null references cliente(id),
 carrinho_id bigint references carrinho(id),
 produto_id bigint not null references produto(id),
 item_carrinho_id bigint references item_carrinho(id) on delete set null,
 item_pedido_id bigint references item_pedido(id),
 quantidade integer not null check(quantidade > 0),
 estado varchar(20) not null check(estado in ('ATIVA','LIBERADA','EXPIRADA','CONSUMIDA')),
 iniciada_em timestamptz not null,
 vence_em timestamptz not null check(vence_em >= iniciada_em),
 check(estado <> 'ATIVA' or num_nonnulls(item_carrinho_id,item_pedido_id)=1)
);
create unique index reserva_item_ativo on reserva_estoque(item_carrinho_id) where estado='ATIVA';
create unique index reserva_pedido_ativo on reserva_estoque(item_pedido_id) where estado='ATIVA';
create index reserva_disponibilidade on reserva_estoque(produto_id,estado,vence_em);
create index reserva_cliente on reserva_estoque(cliente_id,estado);

create table item_retirado_carrinho (
 id bigint generated by default as identity primary key,
 carrinho_id bigint not null references carrinho(id),
 produto_id bigint not null references produto(id),
 produto_nome varchar(150) not null,
 quantidade integer not null check(quantidade > 0),
 motivo varchar(30) not null,
 prazo_minutos bigint not null,
 retirado_em timestamptz not null,
 readicionado boolean not null default false
);
create index retirados_carrinho on item_retirado_carrinho(carrinho_id);
create table notificacao_venda (
 id bigint generated by default as identity primary key,
 cliente_id bigint not null references cliente(id),
 chave varchar(160) not null unique,
 tipo varchar(40) not null,
 mensagem varchar(500) not null,
 criada_em timestamptz not null,
 lida boolean not null default false
);
create index notificacao_cliente on notificacao_venda(cliente_id,criada_em desc);

create table troca (
 id bigint generated by default as identity primary key,
 codigo varchar(30) generated always as ('TRO-' || id::text) stored unique,
 pedido_id bigint not null references pedido(id),
 cliente_id bigint not null references cliente(id),
 integral boolean not null,
 status varchar(30) not null check(status in ('EM_TROCA','TROCA_AUTORIZADA','TROCADO')),
 motivo varchar(500) not null,
 criada_em timestamptz not null,
 autorizada_em timestamptz,
 recebida_em timestamptz,
 retornar_estoque boolean,
 cupom_id bigint unique references cupom(id),
 chave_solicitacao varchar(80),
 resumo_solicitacao varchar(64),
 check(status <> 'TROCADO' or (recebida_em is not null and cupom_id is not null and retornar_estoque is not null))
);
create unique index troca_solicitacao_unica on troca(cliente_id,chave_solicitacao) where chave_solicitacao is not null;
create index troca_pedido on troca(pedido_id);
create table item_troca (
 id bigint generated by default as identity primary key,
 troca_id bigint not null references troca(id),
 item_pedido_id bigint not null references item_pedido(id),
 quantidade integer not null check(quantidade > 0),
 valor_liquido numeric(12,2) not null check(valor_liquido >= 0),
 unique(troca_id,item_pedido_id)
);
create table movimentacao_estoque (
 id bigint generated by default as identity primary key,
 produto_id bigint not null references produto(id),
 tipo varchar(20) not null check(tipo in ('BAIXA','REENTRADA')),
 quantidade integer not null check(quantidade > 0),
 item_pedido_id bigint references item_pedido(id),
 item_troca_id bigint references item_troca(id),
 ocorrida_em timestamptz not null,
 check((tipo='BAIXA' and item_pedido_id is not null and item_troca_id is null)
    or (tipo='REENTRADA' and item_troca_id is not null and item_pedido_id is null))
);
create unique index baixa_unica on movimentacao_estoque(item_pedido_id) where tipo='BAIXA';
create unique index reentrada_unica on movimentacao_estoque(item_troca_id) where tipo='REENTRADA';
alter table transacao_cliente add column origem varchar(20) not null default 'LEGADO';
alter table transacao_cliente add column origem_entidade varchar(30);
alter table transacao_cliente add column origem_id bigint;
create unique index transacao_origem_unica on transacao_cliente(origem_entidade,origem_id) where origem_id is not null;
